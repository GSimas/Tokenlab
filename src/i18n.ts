export type Locale = "pt" | "en";

export function subscribeSystemDark(callback: () => void) {
  if (typeof window === "undefined") return () => {};
  const mq = window.matchMedia("(prefers-color-scheme: dark)");
  mq.addEventListener("change", callback);
  return () => mq.removeEventListener("change", callback);
}

export function getSystemDarkSnapshot() {
  return window.matchMedia("(prefers-color-scheme: dark)").matches;
}

export function getSystemDarkServerSnapshot() {
  return true;
}

export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "pt";
  const stored = typeof localStorage !== "undefined" ? localStorage.getItem("tokenlab-locale") : null;
  if (stored === "pt" || stored === "en") return stored;
  const languages = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
  const preferred = languages.find((lang) => lang) ?? "pt";
  return preferred.toLowerCase().startsWith("pt") ? "pt" : "en";
}

export function fmt(template: string, vars: Record<string, string | number> = {}) {
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in vars ? String(vars[key]) : match));
}

